const lookup = (dict: Dict, key: string): string | undefined => {
  let node: string | Dict | undefined = dict;
  for (const part of key.split(".")) {
    if (typeof node !== "object" || node === null) return undefined;
    node = node[part];
  }
  return typeof node === "string" ? node : undefined;
};

export type Localize = (key: string, vars?: Record<string, string | number>) => string;

export const createLocalize = (language: string | undefined): Localize => {
  const dict = language?.toLowerCase().startsWith("de") ? de : en;
  return (key, vars) => {
    let text = lookup(dict, key) ?? lookup(en, key) ?? key;
    for (const [name, value] of Object.entries(vars ?? {})) {
      text = text.replaceAll(`{${name}}`, String(value));
    }
    return text;
  };
};
